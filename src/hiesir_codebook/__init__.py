"""Extract HIES (Household Income and Expenditure Survey of Iran) questionnaires from the PDF forms."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

__all__ = ["CSV_COLUMNS", "Row", "build", "extract", "extract_year", "main", "write_csv"]

# --- where things live --------------------------------------------------------
# data/     external inputs, not in git (PDFs, hazm's word list) except the
#           household occurrence tables and the PDF list
# curated/  hand-kept decisions: the only files anyone edits; curated/<stage>/
#           holds the decisions applied to output/<stage>/
# output/   generated by `hiesir-codebook build`, tracked, never edited
# reports/  generated review aids, not in git
DATA_DIR = Path("data")
CURATED = Path("curated")
OUTPUT = Path("output")
REPORTS = Path("reports")
EXTRACTED = OUTPUT / "1_extracted"  # PDFs -> CSV, as printed
CORRECTED = OUTPUT / "2_corrected"  # + curated/2_corrected/
ITEMS = OUTPUT / "3_items"  # chains, links and relations across years (+ curated/3_items/)
GROUPS = OUTPUT / "4_groups"  # group headers across years (+ curated/4_groups/)
CURATED_CORRECTED = CURATED / "2_corrected"  # corrections.csv, spelling.csv
CURATED_ITEMS = CURATED / "3_items"  # links.csv, relations.csv
CURATED_GROUPS = CURATED / "4_groups"  # links.csv

# years whose PDF has a usable text layer (1363-1381 are scans; the 1401 PDF
# is a data dictionary, not the questionnaire)
SUPPORTED_YEARS = [1382, *range(1383, 1401), 1402, 1403]

# the extraction code lives in extraction/ (after the paths and years it uses)
from .extraction import CSV_COLUMNS, Row, build, extract, extract_year, write_csv  # noqa: E402


def build_all(data: Path = DATA_DIR, extract_pdfs: bool = True) -> None:
    """Regenerate every stage of output/ in order.

    extract (PDFs -> 1_extracted, skipped when the PDFs are not available)
    -> correct (+ curated/2_corrected -> 2_corrected) -> chains and relations
    (-> 3_items) -> the groups (-> 4_groups) -> the explorer page -> the
    figures of it all (-> metrics.json).
    """
    from . import explorer, metrics
    from .correction import correct, corrections
    from .linking import chains, groups, relations

    if extract_pdfs and (data / "pdf").is_dir():
        for y in SUPPORTED_YEARS:
            build(y, data, EXTRACTED)
        print(f"extracted {len(SUPPORTED_YEARS)} years -> {EXTRACTED}")
        print(f"what each left out or repaired: {EXTRACTED}/reports/report_<year>.csv")
    elif extract_pdfs:
        print(f"no {data / 'pdf'}: keeping {EXTRACTED} as it is")
    else:
        print(f"keeping {EXTRACTED} as it is")
    correct.main([])
    corrections.main([])
    chains.main([])
    relations.main([])
    groups.main([])
    explorer.main([])
    metrics.main([])


def main(argv: list[str] | None = None) -> int:
    # the reports name Persian words: a Windows console's code page cannot show them
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(prog="hiesir-codebook", description=__doc__)
    sub = ap.add_subparsers(dest="command", required=True)
    b = sub.add_parser("build", help="regenerate every stage of output/")
    b.add_argument("--no-extract", action="store_true", help="keep output/1_extracted/, do not read the PDFs")
    b.add_argument("--data", type=Path, default=DATA_DIR, help="folder with pdf/ (default: data/)")
    e = sub.add_parser("extract", help="just extract: the PDFs -> output/1_extracted/")
    e.add_argument("years", nargs="*", type=int, help="survey years (default: all supported)")
    e.add_argument("--data", type=Path, default=DATA_DIR, help="folder with pdf/ (default: data/)")
    e.add_argument("--csv-dir", type=Path, default=EXTRACTED, help=f"default: {EXTRACTED.as_posix()}/")
    sub.add_parser("pdfs", help="download, verify or list the PDFs (pdfs -h)", add_help=False)
    sub.add_parser(
        "hazm", help="download, verify or list hazm's word list and data (hazm -h)", add_help=False
    )
    args, rest = ap.parse_known_args(argv)
    if args.command == "pdfs":
        from .extraction import pdfs

        return pdfs.main(rest)
    if args.command == "hazm":
        from . import hazm_data

        return hazm_data.main(rest)
    if rest:
        ap.error(f"unrecognized arguments: {' '.join(rest)}")
    if args.command == "build":
        build_all(args.data, extract_pdfs=not args.no_extract)
        return 0
    for y in args.years or SUPPORTED_YEARS:
        print(build(y, args.data, args.csv_dir), flush=True)
    return 0

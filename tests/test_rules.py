import pytest

from hiesir_codebook.correction.rules import house_style, standard_spelling, tidy_punctuation
from hiesir_codebook.utils import ZWNJ


@pytest.mark.parametrize(
    ("raw", "tidy"),
    [
        ("آرد ، رشته ،غلات", "آرد، رشته، غلات"),
        ("نان ماشینی(لواش ،سنگک)", "نان ماشینی (لواش، سنگک)"),
        ("ورمیشل ( رشته فرنگی )", "ورمیشل (رشته فرنگی)"),
        ("هویج(ایرانی)چغندر", "هویج (ایرانی) چغندر"),
        ("ویزیت (دولتی) ، ویزیت", "ویزیت (دولتی)، ویزیت"),
        ("خردکردن و..... )", "خردکردن و ...)"),
        ("از قبیل:سبد", "از قبیل: سبد"),
        ("پارافین,وازلین", "پارافین، وازلین"),
        ("سینی، دیس،، کتری", "سینی، دیس، کتری"),
        ("(... نظایر)، سکه، ...", "(... نظایر)، سکه، ..."),
        ("دیس، ، کتری", "دیس، کتری"),
        ("1,000 ریال ساعت 10:30", "1,000 ریال ساعت 10:30"),
        ("انواع ویدئو (VHS)، سی دی", "انواع ویدئو (VHS)، سی دی"),
        ("کاهدان و. . .)", "کاهدان و ...)"),
        ("کله‌پاچه و...وسایر", "کله‌پاچه و ... وسایر"),
        ("در12ماه گذشته", "در 12 ماه گذشته"),
        ("پژو405", "پژو 405"),
        ("MP3، MP4 Player", "MP3، MP4 Player"),
        ("راهنمایی/ متوسطه1و2", "راهنمایی / متوسطه 1 و 2"),
        ("1/2 کیلو", "1/2 کیلو"),
        ("ختنه اطفال و.) و سایر", "ختنه اطفال و ...) و سایر"),
        ("چمپای خوزستان و.", "چمپای خوزستان و ..."),
        ("نوارقلب.نوارمغز ونظایر", "نوارقلب، نوارمغز ونظایر"),
        ("کاکائو. و ترکیبات", "کاکائو و ترکیبات"),
        ("طبقه‌بندی نشده است.", "طبقه‌بندی نشده است"),
        ("نسخه 2.5 و Ver.2", "نسخه 2.5 و Ver.2"),
        ("تجهیزات سمعی- بصری", "تجهیزات سمعی-بصری"),
        ("سمعی -بصری", "سمعی-بصری"),
        ("الف - ب", "الف - ب"),  # a dash, spaced on both sides
    ],
)
def test_tidy_punctuation(raw, tidy):
    assert tidy_punctuation(raw) == tidy


def test_conjunction_after_zwnj_becomes_a_word():
    assert tidy_punctuation("وسایل‌و لوازم") == "وسایل و لوازم"
    assert tidy_punctuation("حمل‌ونقل") == "حمل‌ونقل"  # a compound, not a conjunction


@pytest.mark.parametrize(
    ("raw", "standard"),
    [
        ("دمپائی", "دمپایی"),
        ("روستائیان", "روستاییان"),
        ("خدمات هوائی و دریائی", "خدمات هوایی و دریایی"),
        (f"روستائی{ZWNJ}ها", f"روستایی{ZWNJ}ها"),
        ("گازوئیل", "گازوئیل"),  # a loanword, more letters follow
        ("موزائیک", "موزائیک"),
        ("ارائه", "ارائه"),
        ("جزئی", "جزئی"),  # not after a vowel
        ("پارچه ائی", f"پارچه{ZWNJ}ای"),  # ه + ای, misprinted
        ("مسابقه ایی ورزشی", f"مسابقه{ZWNJ}ای ورزشی"),
        (f"پارچه{ZWNJ}ایی", f"پارچه{ZWNJ}ای"),
        ("کالاهایی", "کالاهایی"),  # the plural + یی
        (f"نوشیدنی{ZWNJ}هایی", f"نوشیدنی{ZWNJ}هایی"),
        ("پرداخت می شود", f"پرداخت می{ZWNJ}شود"),
        ("نمی شوند", f"نمی{ZWNJ}شوند"),
        ("سیمی شود", "سیمی شود"),  # not a prefix
    ],
)
def test_standard_spelling(raw, standard):
    assert standard_spelling(raw) == standard


def test_harakat_go_tanwin_stays():
    assert standard_spelling("وسایل نقاشی، آّبرنگ") == "وسایل نقاشی، آبرنگ"
    assert standard_spelling("خرید قبلاً") == "خرید قبلاً"


def test_house_style_runs_both():
    assert house_style("دمپائی ، کفش") == "دمپایی، کفش"
